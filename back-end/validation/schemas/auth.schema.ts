import * as z from "zod";

export const CreateUser = z.object({
  email: z.email("Електронна пошта повинна мати правильний формат"),
  firstName: z
    .string("Ім'я повинно бути в рядковому форматі")
    .min(2, "Довжина імені повинна бути більше 2-ох символів")
    .max(15, "Довжина імені повинна бути менше 15-ти символів"),
  lastName: z
    .string("Прізвище повинно бути в рядковому форматі")
    .min(2, "Довжина прізвища повинна бути більше 2-ох символів")
    .max(25, "Довжина прізвища повинна бути менше 25-ти символів"),
  gender: z.optional(
    z.enum(["male", "female"], "Стать вказана в неправильному форматі")
  ),
  password: z
    .string("Пароль повинен бути в рядковому форматі")
    .min(8, "Пароль повинен містити не менше 8-ми символів"),
});
