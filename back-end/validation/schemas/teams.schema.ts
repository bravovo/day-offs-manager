import * as z from "zod";

export const ValidateTeam = z.object({
  title: z
    .string("Назва команди повинна бути в рядковому форматі")
    .min(2, "Довжина назви команди повинна бути більше 2-ох символів"),
  maxDayOffs: z
    .number("Максимальна кількість вихідних повинна бути цілим числом від 0")
    .min(0, "Максимальна кількість вихідних повинна бути цілим числом від 0"),
  maxSick: z
    .number("Максимальна кількість лікарняних повинна бути цілим числом від 0")
    .min(0, "Максимальна кількість лікарняних повинна бути цілим числом від 0"),
  system: z.enum(
    ["all-in", "accum"],
    "Значення системи накопичення передано в неправильному форматі"
  ),
});
